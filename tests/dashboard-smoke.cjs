// Node built-in smoke checks for public dashboard, no paid services or dependencies.
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('index.html','utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script, 'inline script exists');
new vm.Script(script, {filename:'index.html:inline.js'});
const data = JSON.parse(fs.readFileSync('governor.json','utf8'));
assert.equal(data.enforcement,'not-connected');
// Live readings change; check the shape, not the values.
for (const side of ['codex', 'claude']) for (const w of ['five_hour', 'week']) {
  const r = data.providers[side][w];
  for (const k of ['observed_remaining_pct', 'estimated_remaining_pct'])
    assert.ok(r[k] === null || (typeof r[k] === 'number' && r[k] >= 0 && r[k] <= 100), `${side}.${w}.${k}`);
}
assert.match(html,/unknown \(stale report\)/);
assert.match(html,/Owner pause active/);
assert.match(html,/Not measured/);
assert.match(html,/Run limits \(D-035, checked by the governor\)/);
const functions = script.slice(script.indexOf('function validPct('),script.indexOf('// Run limits live in budget.json'));
const ctx = vm.createContext({Date,Math,Number,Number: Number});
vm.runInContext(functions,ctx);
assert.equal(ctx.pct(null),'Not measured');
assert.equal(ctx.pct(0),'0.0%');
assert.equal(ctx.pct(101),'Not measured');
const now=Date.now();
const w={reset_at:new Date(now+5*3600e3).toISOString(),_duration:5*3600e3,_final_margin:3};
const policy=data.policy;
assert.equal(ctx.reserveFor(w,policy),20);
assert.ok(ctx.reserveFor({...w,reset_at:new Date(now+15*60e3).toISOString()},policy) < 7);
assert.equal(ctx.reserveFor({...w,reset_at:new Date(now-1000).toISOString()},policy),null);
assert.equal(ctx.reserveFor({...w,reset_at:null},policy),null);
assert.equal(ctx.validPct(-1),false);
assert.equal(ctx.validPct(50),true);
// Run counting must match the governor (governor/budget.py). Cases were generated by the Python code.
const counting = script.slice(script.indexOf('// ---- Run counting'), script.indexOf('// ---- end run counting ----'));
assert.ok(counting.includes('function countRuns('), 'run counting block found');
const rc = vm.createContext({Date, Math, Number, Intl, Map, Object, String, Array, FIVE_H: 5 * 3600e3});
vm.runInContext(counting, rc);
const {cases} = JSON.parse(fs.readFileSync('tests/run-count-cases.json', 'utf8'));
assert.ok(cases.length >= 50, 'parity cases present');
for (const [i, c] of cases.entries()) {
  const now = Date.parse(c.now);
  assert.deepEqual(Array.from(rc.logDates(now)), c.log_dates, `case ${i} log dates`);
  for (const side of ['codex', 'claude']) {
    const got = rc.countRuns(side, c.logs, c.entries, now);
    assert.deepEqual({used: {...got.used}, unreadable: got.unreadable}, c.expected[side], `case ${i} ${side}`);
  }
}
console.log('PASS: HTML script syntax, JSON, missing meters, stale state, pause, reserve ramp/reset boundaries, ' + cases.length + ' governor run-count parity cases');
